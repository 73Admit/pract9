def main() -> None:
    random.seed(42)
    storage.init_db()
    games = recommender.load_games()

    n_q = 0
    for user, queries in QUERIES.items():
        for q in queries:
            results, parsed = recommender.recommend(games, q, 5)
            storage.log_query(user, q, parsed['genres'],
                              results[0] if results else None, source='demo')
            n_q += 1

    known = set(games['steam_appid'])
    n_r = 0
    for user, app_id, rating, text in REVIEWS:
        if app_id in known:
            row = games[games['steam_appid'] == app_id].iloc[0]
            storage.add_review(user, app_id, row['name'], rating, text)
            n_r += 1

    print(f'Добавлено запросов: {n_q}, отзывов: {n_r}')
    info = personal.train_model(games)
    print('Обучение модели:', info)

    qs = storage.query_stats()
    print(f"В базе запросов: {qs['total']}, пользователей: {qs['users']}")
    print('Топ жанров:', qs['top_genres'][:5])


if __name__ == '__main__':
    main()
